#!/usr/bin/env python3
"""
DATA150 Automated Schema Preflight Validator
Compares generated dataset rows against DATA150-SCHEMA-BASELINE.json to guarantee:
1. 0 invented tables.
2. 0 invented columns across all tables.
3. All NOT-NULL columns without defaults are present and valid.
4. Data types match (uuid, numeric, text, boolean, jsonb, timestamp, date).
5. CHECK constraints are satisfied.
6. Primary keys are present, distinct, and valid.
7. Exactly 150 distinct rows per table.
"""
import json
import re
import os
import sys
import uuid
from pathlib import Path
from datetime import datetime, date

def resolve_baseline_path() -> Path:
    env_path = os.environ.get('DATA150_SCHEMA_BASELINE')
    if env_path and Path(env_path).exists():
        return Path(env_path)
    repo_baseline = Path(__file__).resolve().parent.parent.parent / 'docs/verification/data150-schema-baseline.json'
    if repo_baseline.exists():
        return repo_baseline
    cwd_baseline = Path.cwd() / 'docs/verification/data150-schema-baseline.json'
    if cwd_baseline.exists():
        return cwd_baseline
    local_fallback = Path.home() / 'Documents/Codex/2026-10-09/fornexa-data150/DATA150-SCHEMA-BASELINE.json'
    if local_fallback.exists():
        return local_fallback
    return repo_baseline

BASELINE_PATH = resolve_baseline_path()

def load_baseline():
    if not BASELINE_PATH.exists():
        raise FileNotFoundError(f"Baseline not found at {BASELINE_PATH}")
    with open(BASELINE_PATH, 'r', encoding='utf-8') as f:
        data = json.load(f)

    baseline_tables = {}
    for t in data.get('tables', []):
        tname = t['name'].replace('public.', '')
        col_map = {c['name']: c for c in t['columns']}
        baseline_tables[tname] = {
            'name': tname,
            'primary_keys': t.get('primary_keys', []),
            'columns': col_map,
            'initial_rows': t.get('initial_rows', 0),
            'rls_enabled': t.get('rls_enabled', False),
            'foreign_key_constraints': t.get('foreign_key_constraints', [])
        }
    return baseline_tables

def parse_check_allowed_values(check_str):
    """Extracts allowed string values from SQL check constraints like:
    col = ANY (ARRAY['VAL1'::text, 'VAL2'::text])
    """
    if not check_str:
        return None
    m = re.search(r"ARRAY\[(.*?)\]", check_str)
    if m:
        raw_items = m.group(1).split(',')
        allowed = []
        for item in raw_items:
            item_clean = re.sub(r"::\w+", "", item.strip()).strip("'\"")
            allowed.append(item_clean)
        return set(allowed)
    return None

def validate_dataset(dataset, baseline_tables, auth_users=None):
    errors = []
    warnings = []
    stats = {
        'total_tables': len(dataset),
        'total_rows': sum(len(rows) for rows in dataset.values()),
        'tables_with_invented_cols': 0,
        'invented_cols_count': 0,
        'missing_required_cols_count': 0,
        'check_constraint_failures': 0,
        'type_mismatches': 0,
        'foreign_key_violations': 0,
        'unique_violations': 0
    }

    TENANT_ID = "00000000-0000-4000-8000-000000000001"

    # Pre-index primary keys across dataset for FK verification
    table_pks = {}
    table_comp_pks = {}
    for tname, rows in dataset.items():
        if tname not in baseline_tables:
            continue
        pks = baseline_tables[tname]['primary_keys']
        if len(pks) == 1:
            table_pks[tname] = set(r.get(pks[0]) for r in rows if r.get(pks[0]) is not None)
        elif len(pks) > 1:
            table_comp_pks[tname] = set(tuple(r.get(k) for k in pks) for r in rows if all(r.get(k) is not None for k in pks))

    for tname, rows in dataset.items():
        if tname not in baseline_tables:
            errors.append(f"Table '{tname}' does not exist in baseline schema.")
            continue

        table_meta = baseline_tables[tname]
        col_map = table_meta['columns']
        pks = table_meta['primary_keys']

        # Check row count
        if len(rows) != 150:
            errors.append(f"Table '{tname}' has {len(rows)} rows, expected exactly 150.")

        # Check uniqueness of PKs (skip if PK is an identity column generated by DB)
        is_identity_pk = len(pks) == 1 and 'identity' in col_map.get(pks[0], {}).get('options', [])
        if not is_identity_pk:
            seen_pks = set()
            for idx, row in enumerate(rows):
                if len(pks) == 1:
                    pk_val = row.get(pks[0])
                    if pk_val is None:
                        errors.append(f"Table '{tname}' missing PK '{pks[0]}' at row {idx}.")
                    elif pk_val in seen_pks:
                        errors.append(f"Table '{tname}' duplicate PK '{pk_val}' at row {idx}.")
                        stats['unique_violations'] += 1
                    seen_pks.add(pk_val)
                elif len(pks) > 1:
                    pk_val = tuple(row.get(k) for k in pks)
                    if any(v is None for v in pk_val):
                        errors.append(f"Table '{tname}' missing composite PK at row {idx}.")
                    elif pk_val in seen_pks:
                        errors.append(f"Table '{tname}' duplicate composite PK {pk_val} at row {idx}.")
                        stats['unique_violations'] += 1
                    seen_pks.add(pk_val)

        # Check column existence & zero invented columns
        all_row_cols = set()
        for row in rows:
            all_row_cols.update(row.keys())

        invented = all_row_cols - set(col_map.keys())
        if invented:
            stats['tables_with_invented_cols'] += 1
            stats['invented_cols_count'] += len(invented)
            errors.append(f"Table '{tname}' has {len(invented)} invented columns: {sorted(list(invented))}")

        # Check required columns (non-nullable and no auto-identity/generated) - STRICT ERROR
        for col_name, col_meta in col_map.items():
            is_nullable = 'nullable' in col_meta.get('options', [])
            is_identity = 'identity' in col_meta.get('options', [])
            is_generated = 'generated' in col_meta.get('options', [])
            if not is_nullable and not is_identity and not is_generated and col_name not in all_row_cols:
                errors.append(f"Table '{tname}' column '{col_name}' is NOT NULL and missing from dataset rows.")
                stats['missing_required_cols_count'] += 1

        # Check unique columns within dataset
        for col_name, col_meta in col_map.items():
            if 'unique' in col_meta.get('options', []) and col_name in all_row_cols:
                seen_unique = set()
                for idx, row in enumerate(rows):
                    u_val = row.get(col_name)
                    if u_val is not None:
                        if u_val in seen_unique:
                            errors.append(f"Table '{tname}' col '{col_name}' duplicate unique value '{u_val}' at row {idx}.")
                            stats['unique_violations'] += 1
                        seen_unique.add(u_val)

        # Check values, types, and CHECK constraints
        for row_idx, row in enumerate(rows):
            for col_name, val in row.items():
                if col_name not in col_map:
                    continue # already recorded in invented

                col_meta = col_map[col_name]
                dtype = col_meta.get('data_type')

                if val is None:
                    if 'nullable' not in col_meta.get('options', []):
                        errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' has NULL but column is NOT NULL.")
                    continue

                # Type checks
                if dtype == 'uuid':
                    try:
                        uuid.UUID(str(val))
                    except ValueError:
                        errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' invalid UUID '{val}'.")
                        stats['type_mismatches'] += 1
                elif dtype == 'boolean':
                    if not isinstance(val, bool):
                        errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' expected bool, got {type(val)}.")
                        stats['type_mismatches'] += 1
                elif dtype in ('integer', 'bigint', 'smallint'):
                    if not isinstance(val, int) or isinstance(val, bool):
                        errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' expected int, got {type(val)}.")
                        stats['type_mismatches'] += 1
                elif dtype in ('numeric', 'double precision', 'real'):
                    if not isinstance(val, (int, float)) or isinstance(val, bool):
                        errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' expected numeric, got {type(val)}.")
                        stats['type_mismatches'] += 1
                elif dtype == 'date':
                    if isinstance(val, (datetime, date)):
                        pass
                    elif isinstance(val, str):
                        try:
                            date.fromisoformat(val)
                        except ValueError:
                            errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' invalid date '{val}'.")
                            stats['type_mismatches'] += 1
                    else:
                        errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' expected date string, got {type(val)}.")
                        stats['type_mismatches'] += 1
                elif dtype in ('timestamp with time zone', 'timestamp without time zone'):
                    if isinstance(val, datetime):
                        pass
                    elif isinstance(val, str):
                        try:
                            datetime.fromisoformat(val.replace('Z', '+00:00'))
                        except ValueError:
                            errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' invalid timestamp '{val}'.")
                            stats['type_mismatches'] += 1
                    else:
                        errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' expected timestamp string, got {type(val)}.")
                        stats['type_mismatches'] += 1
                elif dtype in ('json', 'jsonb'):
                    if not isinstance(val, (dict, list, str, int, float, bool)):
                        errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' invalid JSON value {type(val)}.")
                        stats['type_mismatches'] += 1
                elif dtype == 'ARRAY' or (isinstance(dtype, str) and dtype.startswith('_')):
                    if not isinstance(val, list):
                        errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' expected list for ARRAY, got {type(val)}.")
                        stats['type_mismatches'] += 1

                # Check constraint check
                check_str = col_meta.get('check')
                if check_str:
                    allowed = parse_check_allowed_values(check_str)
                    if allowed and str(val) not in allowed:
                        errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' value '{val}' violates CHECK: {check_str}")
                        stats['check_constraint_failures'] += 1

                    # Case checks like upper(country::text)
                    if 'upper(' in check_str and isinstance(val, str):
                        if val != val.upper():
                            errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' value '{val}' must be uppercase.")
                            stats['check_constraint_failures'] += 1

                    # Positive checks like > 0 or >= 0
                    if '> 0' in check_str and isinstance(val, (int, float)):
                        if val <= 0:
                            errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' value {val} must be > 0.")
                            stats['check_constraint_failures'] += 1
                    elif '>= 0' in check_str and isinstance(val, (int, float)):
                        if val < 0:
                            errors.append(f"Table '{tname}' row {row_idx} col '{col_name}' value {val} must be >= 0.")
                            stats['check_constraint_failures'] += 1

        # Check Foreign Keys for this table
        for fk in table_meta.get('foreign_key_constraints', []):
            if fk['source_table'].replace('public.', '') != tname:
                continue
            target_t = fk['target_table'].replace('public.', '')
            src_cols = fk['source_columns']
            tgt_cols = fk['target_columns']

            # Check tenant_id reference
            if target_t == 'tenants' and len(src_cols) == 1 and src_cols[0] == 'tenant_id':
                for idx, row in enumerate(rows):
                    if row.get('tenant_id') != TENANT_ID:
                        errors.append(f"Table '{tname}' row {idx} tenant_id '{row.get('tenant_id')}' != target tenant '{TENANT_ID}'.")
                        stats['foreign_key_violations'] += 1

            # Check internal FK to another table within dataset (single or composite, PK or UNIQUE target)
            elif target_t in dataset:
                if len(src_cols) == 1 and len(tgt_cols) == 1:
                    src_col = src_cols[0]
                    tgt_col = tgt_cols[0]
                    target_vals = set(target_row.get(tgt_col) for target_row in dataset[target_t] if target_row.get(tgt_col) is not None)
                    for idx, row in enumerate(rows):
                        fk_val = row.get(src_col)
                        if fk_val is not None and fk_val not in target_vals:
                            errors.append(f"Table '{tname}' row {idx} FK {src_col}='{fk_val}' not found in {target_t}.{tgt_col}.")
                            stats['foreign_key_violations'] += 1
                elif len(src_cols) > 1 and len(src_cols) == len(tgt_cols):
                    target_tuples = set(
                        tuple(target_row.get(c) for c in tgt_cols)
                        for target_row in dataset[target_t]
                    )
                    for idx, row in enumerate(rows):
                        src_tuple = tuple(row.get(c) for c in src_cols)
                        if all(v is not None for v in src_tuple) and src_tuple not in target_tuples:
                            errors.append(f"Table '{tname}' row {idx} composite FK {src_cols}={src_tuple} not found in {target_t}.{tgt_cols}.")
                            stats['foreign_key_violations'] += 1

            # Check external FK to auth.users (fail closed on unverified non-null destination)
            elif target_t in ('auth.users', 'users') or fk.get('target_table') == 'auth.users':
                if len(src_cols) == 1:
                    src_col = src_cols[0]
                    for idx, row in enumerate(rows):
                        val = row.get(src_col)
                        if val is not None:
                            if auth_users is not None and val in auth_users:
                                continue
                            if auth_users is not None:
                                errors.append(f"Table '{tname}' row {idx} FK {src_col}='{val}' not found in verified auth.users.")
                            else:
                                errors.append(f"Table '{tname}' row {idx} FK {src_col}='{val}' references external auth.users without verified destination membership (fail closed).")
                            stats['foreign_key_violations'] += 1

            # Strict fail-closed: any other external target table not in dataset and not tenants
            else:
                for idx, row in enumerate(rows):
                    non_null_vals = [row.get(c) for c in src_cols if row.get(c) is not None]
                    if non_null_vals:
                        errors.append(f"Table '{tname}' row {idx} FK {src_cols}={non_null_vals} references unmanaged external table '{fk['target_table']}' (fail closed).")
                        stats['foreign_key_violations'] += 1

    return errors, warnings, stats

def main():
    baseline_tables = load_baseline()
    dataset_file = Path('docs/verification/data150-dataset.json')
    if not dataset_file.exists():
        print(f"Dataset file {dataset_file} not found.")
        sys.exit(1)

    with open(dataset_file, 'r', encoding='utf-8') as f:
        dataset = json.load(f)

    print(f"Loaded baseline with {len(baseline_tables)} tables.")
    print(f"Loaded dataset with {len(dataset)} tables.")

    errors, warnings, stats = validate_dataset(dataset, baseline_tables)

    print("\n" + "="*50)
    print("PREFLIGHT VALIDATION SUMMARY")
    print("="*50)
    print(f"Total tables: {stats['total_tables']}")
    print(f"Total rows: {stats['total_rows']}")
    print(f"Tables with invented columns: {stats['tables_with_invented_cols']}")
    print(f"Total invented columns: {stats['invented_cols_count']}")
    print(f"Missing required columns (warnings): {stats['missing_required_cols_count']}")
    print(f"Type mismatches: {stats['type_mismatches']}")
    print(f"CHECK constraint failures: {stats['check_constraint_failures']}")
    print(f"Foreign key violations: {stats['foreign_key_violations']}")
    print(f"Total critical errors: {len(errors)}")
    print("="*50)

    if errors:
        print("\nTOP 20 ERRORS:")
        for err in errors[:20]:
            print(f"  ❌ {err}")
        if len(errors) > 20:
            print(f"  ... and {len(errors) - 20} more errors.")
        sys.exit(1)
    else:
        print("\n✅ PREFLIGHT SUCCESS: 0 critical errors, 0 invented columns!")
        sys.exit(0)

if __name__ == '__main__':
    main()
